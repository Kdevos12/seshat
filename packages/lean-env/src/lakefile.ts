import { relative, resolve } from "node:path";
import type { EnvLock, LockPackage } from "./lock.ts";
import type { EnvSpec } from "./spec.ts";

/** The name of the generated root package. */
export const ROOT_PACKAGE = "seshat_env";

const quote = (text: string): string => JSON.stringify(text);

/**
 * The `lakefile.toml` of an environment's project: a root package that requires the environment's
 * packages and, for each dependency that two or more of them list, the commit their manifests
 * agree on. Lake keeps the root's choice over a dependency's, so the agreement the resolver checked
 * is the one the build uses. A dependency only one package lists follows that package's manifest.
 * Local packages are written relative to the project directory `dir`.
 */
export function renderLakefile(spec: EnvSpec, lock: EnvLock, dir: string): string {
  const lines = [
    `# Generated by \`harness lean-env resolve ${lock.name}\` from lean/env/${lock.name}.toml. Do not edit: resolve again.`,
    `# Environment hash ${lock.hash}`,
    `name = ${quote(ROOT_PACKAGE)}`,
    "",
  ];
  for (const pkg of lock.packages) {
    lines.push("[[require]]", `name = ${quote(pkg.name)}`, ...source(spec, pkg, dir), "");
  }
  const shared = lock.dependencies.filter((d) => d.usedBy.length >= 2);
  if (shared.length > 0) lines.push("# Dependencies that several packages list, at the commit they agree on.", "");
  for (const dep of shared) {
    lines.push("[[require]]", `name = ${quote(dep.name)}`, `git = ${quote(dep.url)}`, `rev = ${quote(dep.rev)}`, "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function source(spec: EnvSpec, pkg: LockPackage, dir: string): string[] {
  if (pkg.path !== undefined) return [`path = ${quote(relative(resolve(dir), resolve(spec.dir, pkg.path)) || ".")}`];
  return [`git = ${quote(pkg.git as string)}`, `rev = ${quote(pkg.rev as string)}`];
}
